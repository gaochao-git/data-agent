-- ============================================================
-- 1. 建表语句
-- ============================================================

-- 1.1 用户信息表
DROP TABLE IF EXISTS users;
CREATE TABLE users (
    user_id INT COMMENT '用户ID',
    username STRING COMMENT '用户名',
    email STRING COMMENT '邮箱地址',
    phone STRING COMMENT '手机号码',
    created_at TIMESTAMP COMMENT '创建时间',
    status INT COMMENT '状态'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.2 商品信息表
DROP TABLE IF EXISTS products;
CREATE TABLE products (
    product_id INT COMMENT '商品编号',
    product_name STRING COMMENT '商品名称',
    category STRING COMMENT '商品分类',
    price DECIMAL(10,2) COMMENT '商品价格',
    stock INT COMMENT '库存数量'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.3 订单记录表
DROP TABLE IF EXISTS orders;
CREATE TABLE orders (
    order_id STRING COMMENT '订单编号',
    user_id INT COMMENT '用户ID',
    amount DECIMAL(10,2) COMMENT '订单金额',
    status STRING COMMENT '订单状态',
    order_time TIMESTAMP COMMENT '下单时间',
    pay_time TIMESTAMP COMMENT '支付时间'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.4 商品类别表
DROP TABLE IF EXISTS categories;
CREATE TABLE categories (
    category_id INT COMMENT '类别ID',
    category_name STRING COMMENT '类别名称',
    parent_id INT COMMENT '父类别ID',
    level INT COMMENT '层级: 1-一级, 2-二级',
    description STRING COMMENT '类别描述',
    is_active INT COMMENT '是否启用: 1-是, 0-否'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.5 部门信息表
DROP TABLE IF EXISTS departments;
CREATE TABLE departments (
    dept_id INT COMMENT '部门ID',
    dept_name STRING COMMENT '部门名称',
    manager_name STRING COMMENT '部门经理',
    location STRING COMMENT '办公地点',
    budget DECIMAL(12,2) COMMENT '部门预算'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.6 员工信息表
DROP TABLE IF EXISTS employees;
CREATE TABLE employees (
    emp_id INT COMMENT '员工ID',
    emp_name STRING COMMENT '员工姓名',
    dept_id INT COMMENT '所属部门ID',
    position STRING COMMENT '职位',
    salary DECIMAL(10,2) COMMENT '月薪',
    hire_date TIMESTAMP COMMENT '入职日期',
    email STRING COMMENT '邮箱',
    status INT COMMENT '状态: 1-在职, 0-离职'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.7 订单明细表
DROP TABLE IF EXISTS order_items;
CREATE TABLE order_items (
    item_id STRING COMMENT '明细ID',
    order_id STRING COMMENT '订单编号',
    product_id INT COMMENT '商品ID',
    quantity INT COMMENT '购买数量',
    unit_price DECIMAL(10,2) COMMENT '单价',
    discount DECIMAL(5,2) COMMENT '折扣率',
    subtotal DECIMAL(10,2) COMMENT '小计金额'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.8 销售区域表
DROP TABLE IF EXISTS sales_regions;
CREATE TABLE sales_regions (
    region_id INT COMMENT '区域ID',
    region_name STRING COMMENT '区域名称',
    region_code STRING COMMENT '区域代码',
    sales_manager INT COMMENT '销售经理ID',
    target_amount DECIMAL(12,2) COMMENT '销售目标',
    description STRING COMMENT '区域描述'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.9 用户地址表
DROP TABLE IF EXISTS user_addresses;
CREATE TABLE user_addresses (
    address_id STRING COMMENT '地址ID',
    user_id INT COMMENT '用户ID',
    receiver_name STRING COMMENT '收货人',
    receiver_phone STRING COMMENT '联系电话',
    province STRING COMMENT '省份',
    city STRING COMMENT '城市',
    district STRING COMMENT '区县',
    detail_address STRING COMMENT '详细地址',
    is_default INT COMMENT '是否默认: 1-是, 0-否',
    created_at TIMESTAMP COMMENT '创建时间'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;

-- 1.10 日期转换测试表
DROP TABLE IF EXISTS date_transform_test;
CREATE TABLE date_transform_test (
    id INT COMMENT 'id',
    event_name STRING COMMENT 'event_name',
    event_time TIMESTAMP COMMENT 'event_time'
)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY '\t'
STORED AS ORC;


