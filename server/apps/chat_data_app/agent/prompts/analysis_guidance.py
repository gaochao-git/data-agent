MULTI_STEP_FEWSHOT_PROMPT = """# 多步数据分析示例

以下示例只描述内部查询拆分思路。DSL、SQL、工具参数和 SQL 原始返回行不得输出到用户消息正文；最终只输出摘要、关键数字和判断。

## 示例1：本期与上一期环比
用户：分析本月订单金额环比变化
处理原则：
- 这是数据分析任务，不要求一条 SQL 完成。
- 优先拆成“当前周期”和“对比周期”两次简单查询。
- 每次查询都先调用 `dsl2sql_tool` 校验同一份 DSL，再调用 `semantic_query_tool(dsl=同一份DSL)` 执行。
- 最终基于真实查询结果计算差值和环比，不要凭 SQL 文本推断。

工具顺序：
1. 调用 `dsl2sql_tool` 生成本月订单金额查询。
2. 调用 `semantic_query_tool(dsl=本月DSL)`
3. 调用 `dsl2sql_tool` 生成上月订单金额查询。
4. 调用 `semantic_query_tool(dsl=上月DSL)`
5. 计算：
   - 差值 = 本月订单金额 - 上月订单金额
   - 环比 = 差值 / 上月订单金额
6. 输出当前值、上期值、差值、环比和判断，不输出 DSL、SQL 或原始查询行。

输出注意：
- 如果上期值为 0 或为空，不能输出普通百分比；说明无法计算标准环比，并给出差值。
- 如果某次查询失败或为空，最终结论必须体现失败或空数据事实。

## 示例2：同比
用户：分析今年销售额同比
处理原则：
- 可以拆成“今年销售额”和“去年同期销售额”两次查询。
- 先调用 `get_current_time(detail=false)` 确定当前日期，再构造本年和去年同期的时间范围。
- 如果用户没有明确日期范围，默认使用当前自然年，并说明默认口径。

工具顺序：
1. 查询今年销售额：`dsl2sql_tool(dsl=今年DSL)` -> `semantic_query_tool(dsl=今年DSL)`
2. 查询去年同期销售额：`dsl2sql_tool(dsl=去年同期DSL)` -> `semantic_query_tool(dsl=去年同期DSL)`
3. 计算：
   - 同比差值 = 今年销售额 - 去年同期销售额
   - 同比增长率 = 同比差值 / 去年同期销售额
4. 输出事实、判断和建议。
5. 不输出 DSL、SQL 或原始查询行。
"""
